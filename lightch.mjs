import puppeteer from 'puppeteer-core'
const browser = await puppeteer.launch({ executablePath: '/tmp/chromium', args: ['--no-sandbox','--disable-gpu','--disable-dev-shm-usage','--single-process','--no-zygote'], headless: true, defaultViewport: { width: 1440, height: 1000 } })
const page = await browser.newPage()
await page.goto('http://127.0.0.1:5173/#/', { waitUntil: 'networkidle0' })
await new Promise(x => setTimeout(x, 600))
await page.click('[aria-label="تغییر پوسته"]')
await new Promise(x => setTimeout(x, 500))
await page.goto('http://127.0.0.1:5173/#/chapter/3', { waitUntil: 'networkidle0' })
await new Promise(x => setTimeout(x, 800))
await page.evaluate(() => window.scrollTo(0, 380))
await new Promise(x => setTimeout(x, 400))
await page.screenshot({ path: '/home/user/shots/light-ch3.png' })
await page.goto('http://127.0.0.1:5173/#/chapter/4', { waitUntil: 'networkidle0' })
await new Promise(x => setTimeout(x, 800))
await page.evaluate(() => window.scrollTo(0, 420))
await new Promise(x => setTimeout(x, 400))
await page.screenshot({ path: '/home/user/shots/light-ch4.png' })
await browser.close()
