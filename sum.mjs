import puppeteer from 'puppeteer-core'
const browser = await puppeteer.launch({ executablePath: '/tmp/chromium', args: ['--no-sandbox','--disable-gpu','--disable-dev-shm-usage','--single-process','--no-zygote'], headless: true, defaultViewport: { width: 1280, height: 1000 } })
const page = await browser.newPage()
const errs = []
page.on('pageerror', e => errs.push(e.message))
page.on('console', m => { if (m.type()==='error') errs.push(m.text().slice(0,120)) })
await page.goto('http://127.0.0.1:5173/#/lesson/13', { waitUntil: 'networkidle0' })
await new Promise(x => setTimeout(x, 600))
await page.evaluate(() => [...document.querySelectorAll('button')].find(b => b.textContent?.trim() === 'متن کامل')?.click())
await new Promise(x => setTimeout(x, 700))
await page.evaluate(() => [...document.querySelectorAll('button')].find(b => b.textContent?.trim() === 'خلاصهٔ کتاب')?.click())
await new Promise(x => setTimeout(x, 900))
await page.evaluate(() => window.scrollTo(0, 320))
await new Promise(x => setTimeout(x, 400))
await page.screenshot({ path: '/home/user/shots/summary13.png' })
console.log('len', await page.evaluate(() => document.body.innerText.length))
console.log('ERRS', [...new Set(errs)].slice(0,4))
await browser.close()
