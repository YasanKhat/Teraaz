import puppeteer from 'puppeteer-core'
const b = await puppeteer.launch({ executablePath: '/tmp/chromium', args: ['--no-sandbox','--disable-gpu','--disable-dev-shm-usage','--single-process','--no-zygote'], headless: true, defaultViewport: { width: 1280, height: 1000 } })
const p = await b.newPage()
const errs=[]; p.on('pageerror', e=>errs.push(e.message)); p.on('console', m=>{ if(m.type()==='error') errs.push(m.text().slice(0,110)) })
await p.goto('http://127.0.0.1:5173/#/lesson/13', { waitUntil: 'networkidle0' })
await new Promise(x => setTimeout(x, 800))
await p.evaluate(() => [...document.querySelectorAll('button')].find(b => b.textContent?.trim() === 'خط‌به‌خط')?.click())
await new Promise(x => setTimeout(x, 900))
const first = await p.evaluate(() => document.body.innerText.match(/جملهٔ .* از .*/)?.[0])
console.log('first', first)
await p.screenshot({ path: '/home/user/shots/lines13.png' })
// answer wrongly then check feedback
await p.evaluate(() => [...document.querySelectorAll('button')].find(b => b.textContent?.trim() === 'درست' || b.textContent?.trim() === 'نادرست')?.click())
await new Promise(x => setTimeout(x, 400))
console.log('feedback', await p.evaluate(() => /پاسخ کتاب/.test(document.body.innerText)))
await p.screenshot({ path: '/home/user/shots/lines13b.png' })
await p.evaluate(() => [...document.querySelectorAll('button')].find(b => b.textContent?.includes('جملهٔ بعدی'))?.click())
await new Promise(x => setTimeout(x, 300))
console.log('next', await p.evaluate(() => document.body.innerText.match(/جملهٔ .* از .*/)?.[0]))
// mobile
const m = await b.newPage()
await m.setViewport({ width: 390, height: 844 })
await m.goto('http://127.0.0.1:5173/#/lesson/1', { waitUntil: 'networkidle0' })
await new Promise(x => setTimeout(x, 800))
await m.evaluate(() => [...document.querySelectorAll('button')].find(b => b.textContent?.trim() === 'خط‌به‌خط')?.click())
await new Promise(x => setTimeout(x, 800))
console.log('mobile sw', await m.evaluate(() => document.documentElement.scrollWidth))
await m.screenshot({ path: '/home/user/shots/lines-mobile.png' })
console.log('ERRS', [...new Set(errs)].slice(0,4))
await b.close()
