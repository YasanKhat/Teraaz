import puppeteer from 'puppeteer-core'
const browser = await puppeteer.launch({ executablePath: '/tmp/chromium', args: ['--no-sandbox','--disable-gpu','--disable-dev-shm-usage','--single-process','--no-zygote'], headless: true, defaultViewport: { width: 1280, height: 1000 } })
const page = await browser.newPage()
const errs = []
page.on('pageerror', e => errs.push('PAGE ' + e.message))
page.on('console', m => { if (m.type() === 'error') errs.push('CON ' + m.text().slice(0, 140)) })
await page.goto('http://127.0.0.1:5173/#/lesson/13', { waitUntil: 'networkidle0' })
await new Promise(x => setTimeout(x, 600))
await page.evaluate(() => [...document.querySelectorAll('button')].find(b => b.textContent?.trim().includes('پرسش‌ها'))?.click())
await new Promise(x => setTimeout(x, 1200))
await page.screenshot({ path: '/home/user/shots/bank13.png' })
await page.evaluate(() => [...document.querySelectorAll('button')].filter(b => b.textContent?.trim() === 'درست')[0]?.click())
await new Promise(x => setTimeout(x, 400))
await page.evaluate(() => window.scrollTo(0, 780))
await new Promise(x => setTimeout(x, 400))
await page.screenshot({ path: '/home/user/shots/bank13b.png' })
await page.setViewport({ width: 390, height: 844 })
await new Promise(x => setTimeout(x, 500))
console.log('mobile', await page.evaluate(() => document.documentElement.scrollWidth))
console.log('ERRS', [...new Set(errs)].slice(0,5))
await browser.close()
