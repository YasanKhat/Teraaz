import puppeteer from 'puppeteer-core'
const browser = await puppeteer.launch({ executablePath: '/tmp/chromium', args: ['--no-sandbox','--disable-gpu','--disable-dev-shm-usage','--single-process','--no-zygote'], headless: true, defaultViewport: { width: 1280, height: 1000 } })
const page = await browser.newPage()
const errs = []
page.on('pageerror', e => errs.push(e.message))
page.on('console', m => { if (m.type()==='error') errs.push(m.text().slice(0,140)) })
await page.goto('http://127.0.0.1:5173/#/exams', { waitUntil: 'networkidle0' })
await new Promise(x => setTimeout(x, 700))
console.log('cards', await page.evaluate(() => document.body.innerText.includes('آزمون‌های رسمی کتاب')))
await page.evaluate(() => window.scrollTo(0, 900))
await new Promise(x => setTimeout(x, 300))
await page.screenshot({ path: '/home/user/shots/papers-list.png' })
await page.goto('http://127.0.0.1:5173/#/paper/p3', { waitUntil: 'networkidle0' })
await new Promise(x => setTimeout(x, 800))
await page.screenshot({ path: '/home/user/shots/paper3.png' })
await page.evaluate(() => [...document.querySelectorAll('button')].find(b => b.textContent?.includes('دیدن پاسخنامهٔ رسمی'))?.click())
await new Promise(x => setTimeout(x, 400))
await page.evaluate(() => window.scrollTo(0, document.body.scrollHeight))
await new Promise(x => setTimeout(x, 300))
await page.screenshot({ path: '/home/user/shots/paper3-keys.png' })
// mobile overflow
await page.setViewport({ width: 390, height: 844 })
await page.goto('http://127.0.0.1:5173/#/paper/p1', { waitUntil: 'networkidle0' })
await new Promise(x => setTimeout(x, 800))
console.log('mobile', await page.evaluate(() => [document.documentElement.scrollWidth, document.body.scrollWidth]))
console.log('ERRS', [...new Set(errs)].slice(0,5))
await browser.close()
