import puppeteer from 'puppeteer-core'
const browser = await puppeteer.launch({ executablePath: '/tmp/chromium', args: ['--no-sandbox','--disable-gpu','--disable-dev-shm-usage','--single-process','--no-zygote'], headless: true, defaultViewport: { width: 1280, height: 1000 } })
const page = await browser.newPage()
const errs = []
page.on('pageerror', e => errs.push('PAGE ' + e.message))
page.on('console', m => { if (m.type() === 'error') errs.push('CON ' + m.text().slice(0, 140)) })
await page.goto('http://127.0.0.1:5173/#/lesson/3', { waitUntil: 'networkidle0' })
await new Promise(x => setTimeout(x, 700))
await page.evaluate(() => [...document.querySelectorAll('button')].find(b => b.textContent?.trim() === 'متن کامل')?.click())
await new Promise(x => setTimeout(x, 1600))
const len = await page.evaluate(() => document.body.innerText.length)
console.log('text len', len)
console.log('has book heading', await page.evaluate(() => document.body.innerText.includes('شبه‌جزیره عربستان در آستانه ظهور اسلام')))
await page.screenshot({ path: '/home/user/shots/book3.png' })
await page.evaluate(() => window.scrollTo(0, 1400))
await new Promise(x => setTimeout(x, 500))
await page.screenshot({ path: '/home/user/shots/book3b.png' })
await page.evaluate(() => [...document.querySelectorAll('button')].find(b => b.textContent?.includes('فهرست درس'))?.click())
await new Promise(x => setTimeout(x, 500))
await page.screenshot({ path: '/home/user/shots/book3toc.png' })
console.log('ERRS', [...new Set(errs)].slice(0,5))
await browser.close()
