import puppeteer from 'puppeteer-core'
const browser = await puppeteer.launch({ executablePath: '/tmp/chromium', args: ['--no-sandbox','--disable-gpu','--disable-dev-shm-usage','--single-process','--no-zygote'], headless: true, defaultViewport: { width: 1280, height: 950 } })
const page = await browser.newPage()
page.on('console', m => console.log('C', m.type(), m.text().slice(0, 200)))
page.on('pageerror', e => console.log('PAGEERR', e.message))
await page.goto('http://127.0.0.1:5173/#/lesson/3', { waitUntil: 'networkidle0' })
await new Promise(x => setTimeout(x, 500))
await page.evaluate(() => [...document.querySelectorAll('button')].find(b => b.textContent?.trim() === 'متن کامل')?.click())
await new Promise(x => setTimeout(x, 1500))
const info = await page.evaluate(() => ({ articles: document.querySelectorAll('article[aria-label]').length, prose: document.querySelectorAll('.lesson-prose').length, txt: document.body.innerText.slice(900, 1500) }))
console.log(JSON.stringify(info, null, 1))
await browser.close()
